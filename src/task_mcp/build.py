"""build: write a standalone MCP server (server.py + plan.yaml + sources.yaml) from a plan."""
import shutil
from pathlib import Path

import yaml

from .plan import load_plan

HEADER = '''"""Generated by task-mcp from plan.yaml. Edit the plan and rebuild instead of editing this file."""
import json
import os
from pathlib import Path
from typing import Annotated

from mcp.server.mcpserver import MCPServer
from mcp.types import ToolAnnotations
from pydantic import Field

from task_mcp.extract import Extractor
from task_mcp.plan import load_plan, validate
from task_mcp.providers import ollama_complete
from task_mcp.runtime import call_tool
from task_mcp.sources import LiveBackend, load_sources

HERE = Path(__file__).parent
PLAN = load_plan(HERE / "plan.yaml")
SRC = load_sources(PLAN["sources_path"])
if ERRS := validate(PLAN, SRC):  # plan.yaml may have been edited after build
    raise ValueError("plan.yaml is invalid: " + "; ".join(ERRS))
EXTRACTOR = Extractor(PLAN, ollama_complete(os.environ.get("TASK_MCP_EXTRACT_MODEL", "gemma4:12b"), num_ctx=16384,
                                       json_mode=True, think=False, max_out=1500),
                      HERE / "cache")
BACKEND = LiveBackend()
LOG = HERE / "fallback.jsonl"
READ_ONLY = ToolAnnotations(read_only_hint=True)
FIELDS_DOC = "Optional: names of dropped fields to return raw, by path (e.g. updated_at)."
server = MCPServer({name!r})


def _call(name, args):
    return json.dumps(call_tool(PLAN, SRC, name, args, BACKEND, EXTRACTOR, LOG))
'''

FALLBACK_NOTE = "\n\nAny dropped field can be requested by path with the `fields` param."


def _ident(name, what):
    if not str(name).isidentifier():
        raise ValueError(f"{what} {name!r} is not a valid Python identifier")
    return name


def _tool_source(t):
    name = _ident(t["name"], "tool name")
    params = t.get("params") or {}
    args = []
    for pname, p in sorted(params.items(), key=lambda kv: not kv[1].get("required")):
        _ident(pname, "param")
        typ = "str" if p.get("required") else "str | None"
        default = "" if p.get("required") else " = None"
        args.append(f"{pname}: Annotated[{typ}, Field(description={p.get('description', '')!r})]{default}")
    args.append("fields: Annotated[list[str] | None, Field(description=FIELDS_DOC)] = None")
    doc = (t.get("description") or name) + FALLBACK_NOTE
    names = ", ".join(f"{p!r}: {p}" for p in [*params, "fields"])
    return (f"\n\n@server.tool(annotations=READ_ONLY, description={doc!r})\n"
            f"def {name}({', '.join(args)}) -> str:\n"
            f"    return _call({name!r}, {{{names}}})\n")


def build(plan_path, out_dir):
    plan = load_plan(plan_path)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(plan["sources_path"], out / "sources.yaml")
    copy = {k: v for k, v in plan.items() if k != "sources_path"}
    copy["sources"] = "sources.yaml"
    (out / "plan.yaml").write_text(yaml.safe_dump(copy, sort_keys=False, allow_unicode=True))
    src = HEADER.replace("{name!r}", repr(f"{plan['api']}-lean"))
    src += "".join(_tool_source(t) for t in plan["tools"])
    src += '\n\nif __name__ == "__main__":\n    server.run()\n'
    path = out / "server.py"
    path.write_text(src)
    return path
